package mthree.com.fullstackschool.dao;

import mthree.com.fullstackschool.dao.mappers.CourseMapper;
import mthree.com.fullstackschool.model.Course;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.stereotype.Repository;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.List;

@Repository
public class CourseDaoImpl implements CourseDao {

    private final JdbcTemplate jdbcTemplate;

    public CourseDaoImpl(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public Course createNewCourse(Course course) {
        //YOUR CODE STARTS HERE

        // cid is AUTO_INCREMENT, so it is left out of the INSERT and read back from the key holder.
        final String sql = """
                           INSERT INTO course (courseCode, courseDesc, teacherId)
                           VALUES (?, ?, ?)
                           """;

        // This is used to hold the ID generated by the database

        GeneratedKeyHolder keyHolder = new GeneratedKeyHolder();

        // 1, 2, 3 numbers refer to the position of the ? placeholders in your SQL
        // Without requesting generated keys, it wouldn't be able to retrieve the new cid 

        jdbcTemplate.update(connection -> {
            PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            statement.setString(1, course.getCourseName());
            statement.setString(2, course.getCourseDesc());
            statement.setInt(3, course.getTeacherId());
            return statement;
        }, keyHolder);

        course.setCourseId(keyHolder.getKey().intValue());
        return course;

        //YOUR CODE ENDS HERE
    }

    @Override
    public List<Course> getAllCourses() {
        //YOUR CODE STARTS HERE

       // CourseMapper converts each row of the result set into a Course.

         final String sql = """
                            SELECT * 
                            FROM course
                            """;

        return jdbcTemplate.query(sql, new CourseMapper());

        //YOUR CODE ENDS HERE
    }

    @Override
    public Course findCourseById(int id) {
        //YOUR CODE STARTS HERE

        // ? is a placeholder for a value that will be supplied later.
        final String sql = """
                           SELECT *
                           FROM course
                           WHERE cid = ?
                           """;

        return jdbcTemplate.queryForObject(sql, new CourseMapper(), id);

        //YOUR CODE ENDS HERE
    }

    @Override
    public void updateCourse(Course course) {
        //YOUR CODE STARTS HERE

        // The arguments fill the ? placeholders in order, so cid goes last.
        // No CourseMapper here: UPDATE returns no rows, so there is nothing to map.
        
        final String sql = """
                           UPDATE course
                           SET courseCode = ?, courseDesc = ?, teacherId = ?
                           WHERE cid = ?
                           """;

        jdbcTemplate.update(sql,
                course.getCourseName(),
                course.getCourseDesc(),
                course.getTeacherId(),
                course.getCourseId());

        //YOUR CODE ENDS HERE
    }

    @Override
    public void deleteCourse(int id) {
        //YOUR CODE STARTS HERE

        // DELETE also goes through update(), since it changes data and returns no rows.
        final String sql = """
                           DELETE FROM course
                           WHERE cid = ?
                           """;

        jdbcTemplate.update(sql, id);

        //YOUR CODE ENDS HERE
    }

    @Override
    public void deleteAllStudentsFromCourse(int courseId) {
        //YOUR CODE STARTS HERE

        // Removes the enrolments only; the students themselves stay in the student table.
        final String sql = """
                           DELETE FROM course_student
                           WHERE course_id = ?
                           """;

        jdbcTemplate.update(sql, courseId);

        //YOUR CODE ENDS HERE
    }
}
