package mthree.com.fullstackschool.dao;

import mthree.com.fullstackschool.dao.mappers.TeacherMapper;
import mthree.com.fullstackschool.model.Teacher;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.stereotype.Repository;

import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.List;

@Repository
public class TeacherDaoImpl implements TeacherDao {

    private final JdbcTemplate jdbcTemplate;

    public TeacherDaoImpl(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public Teacher createNewTeacher(Teacher teacher) {
        //YOUR CODE STARTS HERE

        // tid is AUTO_INCREMENT, so it is left out of the INSERT and read back from the key holder.
        final String sql = """
                           INSERT INTO teacher (tFName, tLName, dept)
                           VALUES (?, ?, ?)
                           """;

        // This is used to hold the ID generated by the database
        GeneratedKeyHolder keyHolder = new GeneratedKeyHolder();

        // 1, 2, 3 refer to the position of the ? placeholders in the SQL
        jdbcTemplate.update(connection -> {
            PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            statement.setString(1, teacher.getTeacherFName());
            statement.setString(2, teacher.getTeacherLName());
            statement.setString(3, teacher.getDept());
            return statement;
        }, keyHolder);

        teacher.setTeacherId(keyHolder.getKey().intValue());
        return teacher;

        //YOUR CODE ENDS HERE
    }

    @Override
    public List<Teacher> getAllTeachers() {
        //YOUR CODE STARTS HERE

        // TeacherMapper converts each row of the result set into a Teacher.
        final String sql = """
                           SELECT *
                           FROM teacher
                           """;

        return jdbcTemplate.query(sql, new TeacherMapper());

        //YOUR CODE ENDS HERE
    }

    @Override
    public Teacher findTeacherById(int id) {
        //YOUR CODE STARTS HERE

        // ? is a placeholder for a value that will be supplied later.
        final String sql = """
                           SELECT *
                           FROM teacher
                           WHERE tid = ?
                           """;

        return jdbcTemplate.queryForObject(sql, new TeacherMapper(), id);

        //YOUR CODE ENDS HERE
    }

    @Override
    public void updateTeacher(Teacher t) {
        //YOUR CODE STARTS HERE

        // The arguments fill the ? placeholders in order, so tid goes last.
        final String sql = """
                           UPDATE teacher
                           SET tFName = ?, tLName = ?, dept = ?
                           WHERE tid = ?
                           """;

        jdbcTemplate.update(sql,
                t.getTeacherFName(),
                t.getTeacherLName(),
                t.getDept(),
                t.getTeacherId());

        //YOUR CODE ENDS HERE
    }

    @Override
    public void deleteTeacher(int id) {
        //YOUR CODE STARTS HERE

        // DELETE also goes through update(), since it changes data and returns no rows.
        final String sql = """
                           DELETE FROM teacher
                           WHERE tid = ?
                           """;

        jdbcTemplate.update(sql, id);

        //YOUR CODE ENDS HERE
    }
}
